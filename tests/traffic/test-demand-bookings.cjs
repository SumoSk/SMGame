'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const source=fs.readFileSync(require('node:path').join(__dirname,'../../dist/game.js'),'utf8');
const demand=source.slice(source.indexOf('function cityDemand(){'),source.indexOf('function cityAdvice('));
const counts=source.slice(source.indexOf('function compactDemandCounts('),source.indexOf('function updateCityAdvisor('));
const fixture=Function('state','CATALOG','KINDS','ensurePerformance','homeImmigrationLocks',demand+counts+'return {cityDemand,compactDemandCounts};');
const catalog={mall:{kind:'mall',service:40},house:{kind:'home',residents:10},office:{kind:'office',jobs:5}};
const kinds=Object.fromEntries(['shop','restaurant','mall','park','pub','casino'].map(k=>[k,{name:k}]));
const state={time:600,buildings:new Map(),citizens:new Map(),vehicles:new Map()};
const complaints={};const api=fixture(state,catalog,kinds,()=>({complaints}),()=>0);
const mall={key:'mall',visitors:new Set(),reservedService:0,workers:new Set()};
state.buildings.set(1,mall);
const row=()=>api.cityDemand().services.find(r=>r.kind==='mall');
const calc=()=>{const r=row();return api.compactDemandCounts(r.capacity,r.used+r.reserved,r.capacityRequests);};
for(let i=1;i<=16;i++)state.citizens.set(i,{id:i,resident:true,profile:{trait:3},homeId:2});
complaints.route={kind:'mall',reason:'route',people:[...state.citizens.keys()]};
assert.deepEqual(calc(),{capacity:40,booked:0,missing:0});
for(let i=1;i<=16;i++){const c=state.citizens.get(i);c.vehicleId=i;state.vehicles.set(i,{id:i,kind:'leisure',toId:1,serviceKind:'mall',serviceReservation:true,departureNoRoute:true});}
mall.reservedService=16;complaints.full={kind:'mall',reason:'full',people:[...state.citizens.keys()]};
assert.deepEqual(calc(),{capacity:40,booked:16,missing:0});
mall.reservedService=40;
for(let i=17;i<=32;i++)state.citizens.set(i,{id:i,resident:true,profile:{trait:3},homeId:2,pending:{action:'leisure',kind:'mall',expires:1000}});
complaints.full.people.push(...Array.from({length:16},(_,i)=>17+i));
assert.deepEqual(calc(),{capacity:40,booked:40,missing:16});
mall.reservedService=30;assert.deepEqual(calc(),{capacity:40,booked:30,missing:6});
assert.deepEqual(api.compactDemandCounts(40,0,16),{capacity:40,booked:0,missing:0});
assert.deepEqual(api.compactDemandCounts(0,0,16),{capacity:0,booked:0,missing:16});
assert.deepEqual(api.compactDemandCounts(10,8,3),{capacity:10,booked:8,missing:1});
console.log('Booked places, blocked routes and actual capacity deficits passed.');
