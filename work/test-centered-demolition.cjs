'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const stub=fs.readFileSync('work/test-ipad-controls.cjs','utf8').split("game.selectTool('small');")[0];
const {game:g,get}=new Function('require',stub+'return {game,get};')(require);
const gameSource=fs.readFileSync('dist/game.js','utf8');
const rule=fs.readFileSync('dist/style.css','utf8').split('#dialog.demolition-confirm{').at(-1).split('}')[0];
assert.match(rule,/left:50%!important/,'dialog anchored to horizontal viewport midpoint');
assert.match(rule,/top:50%!important/,'dialog anchored to vertical viewport midpoint');
assert.match(rule,/transform:translate\(-50%,-50%\)!important/,'dialog translates by half its own size');
assert.match(rule,/max-height:[^;]*100dvh/,'small screens constrain the confirmation to the viewport');
const prompt=gameSource.slice(gameSource.indexOf('function confirmDemolition('),gameSource.indexOf('function confirmAction('));
assert(prompt.includes("dialog.classList.add('demolition-confirm')"),'destructive prompt keeps its dedicated style');
assert(!prompt.includes('positionConstructionDialog('),'demolition must not anchor next to the pointer');
assert(!prompt.includes("classList.add('construction-confirm')"),'no construction positioning');
const dialog=get('dialog');
const checkOpen=(name)=>{
 assert.equal(dialog.open,true,name+' should ask first');
 assert(!dialog.style.left&&!dialog.style.top,name+' must not set inline pointer coordinates');
 assert(get('dialogContent').innerHTML.includes('รื้อ'),name+' explains demolition');
 assert(get('dialogContent').innerHTML.includes('id="cancelDialog"'));
 assert(get('dialogContent').innerHTML.includes('id="confirmDialog"'));
};
const building=[...g.state.buildings.values()][0];
assert(building,'test city has a building');
const buildingsBefore=g.state.buildings.size;
assert(g.demolishBuilding(building,false,{x:1,y:6}),'building confirmation opens');
checkOpen('building');
assert.equal(g.state.buildings.size,buildingsBefore,'building remains before confirmation');
get('cancelDialog').onclick();
assert.equal(dialog.open,false);
assert.equal(g.state.buildings.size,buildingsBefore,'building cancellation preserves state');
g.reset();g.state.roads.clear();
const node=g.id(168,157);g.state.roads.set(node,{type:'small',main:false,links:new Set(),load:0,wait:0});
assert(g.demolishRoad(node,false,{x:990,y:730}),'road confirmation opens');
checkOpen('road');
assert(g.state.roads.has(node),'road remains pending approval');
get('confirmDialog').onclick();
assert.equal(dialog.open,false);
assert(!g.state.roads.has(node),'road deleted only after explicit confirmation');
console.log(JSON.stringify({passed:true,placement:'center',buildingCancel:true,roadConfirm:true,noPointerAnchoring:true}));
