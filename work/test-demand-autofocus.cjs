const fs=require('node:fs'),assert=require('node:assert/strict');
const fixture=fs.readFileSync('work/test-tourism.cjs','utf8').split('const results=[]')[0];
const {game:g,get}=new Function('require',fixture+'return boot();')(require);
const panel=get('dummy');
panel.clientHeight=100;panel.scrollHeight=450;panel.clientWidth=160;panel.scrollWidth=160;
panel.scrollTop=0;panel.scrollLeft=0;
const selected=[],moves=[];
panel.getBoundingClientRect=()=>({top:0,bottom:100,left:0,right:160,width:160,height:100});
panel.querySelector=selector=>{
 selected.push(selector);
 return{getBoundingClientRect:()=>({top:260,bottom:280,left:240,right:280,width:40,height:20})};
};
panel.scrollTo=options=>{moves.push(options);if(options.top!=null)panel.scrollTop=options.top;if(options.left!=null)panel.scrollLeft=options.left;};
g.focusDemandShortage([{kind:'home',waiting:4},{kind:'restaurant',waiting:12},{kind:'casino',waiting:31}]);
assert(selected.at(-1).includes('casino'),'Largest shortage must win');
assert(moves.at(-1).top>0,'Scroll vertically');
assert.equal(moves.at(-1).behavior,'instant','Do not run long smooth animations');
const count=moves.length;
g.demandFocusState.pointerDown=true;
g.focusDemandShortage([{kind:'restaurant',waiting:100}]);
assert.equal(moves.length,count,'Dragging must pause');
g.demandFocusState.pointerDown=false;
g.demandFocusState.freezeUntil=Date.now()+15000;
g.focusDemandShortage([{kind:'restaurant',waiting:100}]);
assert.equal(moves.length,count,'User hold must pause');
g.demandFocusState.freezeUntil=0;g.demandFocusState.hover=false;
panel.scrollHeight=100;panel.scrollWidth=450;panel.scrollTop=0;panel.scrollLeft=0;
g.focusDemandShortage([{kind:'restaurant',waiting:100}]);
assert(selected.at(-1).includes('restaurant'),'Changed highest shortage must win');
assert(moves.at(-1).left>0,'Scroll horizontally');
const after=moves.length;
g.focusDemandShortage([{kind:'restaurant',waiting:100}]);
assert.equal(after,moves.length,'Do not scroll repeatedly for an unchanged priority');
g.focusDemandShortage([{kind:'casino',waiting:0}]);
assert.equal(after,moves.length,'No shortage: no movement');
// Refreshing needs must remain safe in the minimal DOM test harness.
assert.doesNotThrow(()=>g.updateCityAdvisor());
console.log('PASS v2 demand focus: top priority, drag/hover hold, both axes, throttle and safe UI update');
