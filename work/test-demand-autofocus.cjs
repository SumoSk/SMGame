const fs=require('node:fs'),assert=require('node:assert/strict');
const fixture=fs.readFileSync('work/test-tourism.cjs','utf8').split('const results=[]')[0];
const {game:g,get}=new Function('require',fixture+'return boot();')(require);
const panel=get('dummy');
panel.clientHeight=100;panel.scrollHeight=450;panel.clientWidth=160;panel.scrollWidth=160;
panel.scrollTop=0;panel.scrollLeft=0;
let chosen=[],moves=[];
panel.getBoundingClientRect=()=>({top:0,bottom:100,left:0,right:160,width:160,height:100});
panel.querySelector=selector=>{
 chosen.push(selector);
 return {getBoundingClientRect:()=>({top:260,bottom:280,left:240,right:280,width:40,height:20})};
};
panel.scrollTo=options=>{moves.push(options);if(options.top!=null)panel.scrollTop=options.top;if(options.left!=null)panel.scrollLeft=options.left;};
const demands=[{kind:'home',waiting:4},{kind:'restaurant',waiting:12},{kind:'casino',waiting:31}];
g.focusLargestUnmetDemand(demands);
assert(chosen.at(-1).includes('casino'),'Largest shortage must lead');
assert(moves.at(-1).top>0,'Scroll vertically to largest shortage');
const count=moves.length;
g.demandAutoFocus.held=true;
g.demandAutoFocus.lastCheck=0;
g.focusLargestUnmetDemand([{kind:'restaurant',waiting:100}]);
assert.equal(moves.length,count,'Dragging must pause auto-scroll');
g.demandAutoFocus.held=false;
g.demandAutoFocus.holdUntil=Date.now()+10000;
g.focusLargestUnmetDemand([{kind:'restaurant',waiting:100}]);
assert.equal(moves.length,count,'Manual hold must be respected');
g.demandAutoFocus.holdUntil=0;g.demandAutoFocus.lastCheck=0;
panel.scrollHeight=100;panel.scrollWidth=450;
panel.scrollTop=0;panel.scrollLeft=0;
g.focusLargestUnmetDemand([{kind:'restaurant',waiting:100}]);
assert(chosen.at(-1).includes('restaurant'),'Current top priority selected');
assert(moves.at(-1).left>0,'Scroll horizontally on compact layouts');
const before=moves.length;
g.focusLargestUnmetDemand([{kind:'casino',waiting:0}]);
assert.equal(moves.length,before,'No shortage means no movement');
console.log('PASS: biggest unmet demand, hold during interaction, vertical/horizontal, no unnecessary scroll');
