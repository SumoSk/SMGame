'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const prefix=fs.readFileSync('work/test-tourism.cjs','utf8').split('const results=[]')[0];
const {game:g,get}=new Function('require',prefix+'return boot();')(require);
const html=fs.readFileSync('index.html','utf8'),css=fs.readFileSync('dist/style.css','utf8');
const before=JSON.parse(g.snapshot());
const keys=['roads','home','work','food','leisure','casino','landscape','hotel'];
assert.equal(get('categories').innerHTML,'','redundant Buildings/Landscape/City Data group navigation removed');
for(const key of keys)assert(get('subcategories').innerHTML.includes('data-category="'+key+'"'),'missing primary build category '+key);
assert(!get('subcategories').hidden,'primary construction tabs always visible');
assert(get('tools').innerHTML.includes('data-tool="small"'),'road construction visible by default');
get('subcategories').onclick({target:{closest:()=>({dataset:{category:'landscape'}})}});
assert(get('tools').innerHTML.includes('data-tool="tree:shade"'),'landscape tools available as a build category');
get('subcategories').onclick({target:{closest:()=>({dataset:{category:'food'}})}});
assert(get('tools').innerHTML.includes('data-tool="shop_small"'),'business construction retains its tools');
get('subcategories').onclick({target:{closest:()=>({dataset:{category:'roads'}})}});
assert(get('tools').innerHTML.includes('data-tool="large"'),'can return to road construction');
assert(!get('tools').innerHTML.includes('data-tool="sendAi"'),'Report tools not present in construction');
assert(!get('tools').innerHTML.includes('data-tool="cityReport"'),'City data dock removed');
g.openMainMenu();
assert(get('dialog').open,'menu opens');
const main=get('dialogContent').innerHTML;
assert(main.includes('class="smcity-menu-list"'),'main menu has distinct centering marker');
assert(main.includes('id="reportMenu"'),'Report is entry in main menu');
assert(!main.includes('data-report-action='),'Report details not in main menu');
get('reportMenu').onclick();
const report=get('dialogContent').innerHTML;
assert(report.includes('class="smcity-report-list"'),'Report is its own left information window');
for(const key of ['sendAi','cityReport','incidentLog'])assert(report.includes('data-report-action="'+key+'"'),key+' migrated to Report');
assert.equal(typeof get('dialogContent').onclick,'function','Report items have working event handler');
const click=key=>get('dialogContent').onclick({target:{closest:()=>({dataset:{reportAction:key}})}});
click('cityReport');
assert(get('dialogContent').innerHTML.includes('ตรวจเมือง / รายงานบัค'),'Report opens real city diagnostics');
assert.equal(get('dialogContent').onclick,null,'Report handlers cleared on child dialog');
g.openMainMenu();get('reportMenu').onclick();
get('reportMenuBack').onclick();
assert(get('dialogContent').innerHTML.includes('id="reportMenu"'),'back returns to centered main menu');
get('menuClose').onclick();
assert(!get('dialog').open,'close returns to game');
assert(css.includes('body>.bottom .builder-zone .build-dock #categories{\n display:none!important'),'old dock group row hidden');
assert(css.includes('body>.bottom .builder-zone .dock-context #subcategories::before'),'prominent construction row visible');
assert(css.includes('#dialog:not(.construction-confirm):has(.smcity-menu-list){'),'only main menu gets centered selector');
assert(css.includes('left:50%!important;right:auto!important;'),'main menu centered horizontally');
assert(css.includes('top:50%!important;bottom:auto!important;'),'main menu centered vertically');
assert(css.includes('#dialog .smcity-report-list'),'separate report styling');
assert(css.includes('#dialog:not(.construction-confirm){\n position:fixed!important;\n left:calc(77px'),'other information windows still open by left rail');
const after=JSON.parse(g.snapshot());
for(const key of ['money','city','time','roads','buildings','citizens','vehicles','signals'])assert.deepEqual(after[key],before[key],'UI menus must not mutate city '+key);
console.log('Build/Report navigation passed: one construction tier, landscaping, Report actions, centered Main Menu, left Report, preserved city.');
