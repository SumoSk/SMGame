'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const prefix=fs.readFileSync('work/test-tourism.cjs','utf8').split('const results=[]')[0];
const {city}=new Function('require',prefix+'return {city};')(require);
const {game:g,get,restaurant:b}=city();
// Center this fixture's restaurant in view; it is otherwise off the 2D test canvas.
g.cam.x=b.x;g.cam.y=b.y;
const toolbar=get('buildingQuickActions');
toolbar.dataset={};
const move=get('buildingQuickMove'),demolish=get('buildingQuickDemolish');
const pick=()=>{
 const at=g.screen(b.x+.7,b.y+.7);
 g.inspectAt(at[0],at[1]);
 assert.equal(g.selected?.kind,'building','must select building by tapping its plot');
 assert.equal(g.selected.id,b.id);
 g.updateBuildingQuickActions();
 assert.equal(toolbar.hidden,false,'buttons should appear on selected building');
 assert.equal(toolbar.dataset.buildingId,String(b.id));
 assert(toolbar.style.left?.endsWith('px')&&toolbar.style.top?.endsWith('px'),'buttons should follow screen coordinates');
};
pick();
const oldX=toolbar.style.left;
g.cam.x+=8;
g.updateBuildingQuickActions();
assert.notEqual(toolbar.style.left,oldX,'button position tracks panning');
const source=fs.readFileSync('dist/game.js','utf8'),markup=fs.readFileSync('index.html','utf8');
assert(markup.includes('id="buildingQuickMove"')&&markup.includes('id="buildingQuickDemolish"'));
assert(source.includes("event.target?.closest?.('#buildingQuickActions')"),'tap on buttons must not be treated as outside tap');
move.onclick();
assert.equal(g.movingBuildingId,b.id,'move icon invokes existing relocation tool');
assert.equal(g.state.buildings.has(b.id),true,'entering move mode must not alter the building');
g.updateBuildingQuickActions();
assert.equal(toolbar.hidden,true,'hide buttons during relocation');
get('cancelMoveBuilding').onclick();
assert.equal(g.movingBuildingId,null,'relocation can be cancelled');
pick();
demolish.onclick();
assert.equal(g.state.buildings.has(b.id),true,'demolish icon must not delete immediately');
assert.equal(get('dialog').open,true,'demolish icon must present confirmation');
assert(get('dialogContent').innerHTML.includes('รื้อ'),'confirmation should explain demolition');
g.updateBuildingQuickActions();
assert.equal(toolbar.hidden,true,'hide buttons behind confirmation dialog');
get('cancelDialog').onclick();
assert.equal(g.state.buildings.has(b.id),true,'cancelling demolition keeps the building');
g.reset();
g.updateBuildingQuickActions();
assert.equal(toolbar.hidden,true,'no orphan buttons after restarting a city');
console.log('On-building action buttons passed: select, camera tracking, safe move, confirm demolition, cancel, cleanup.');
