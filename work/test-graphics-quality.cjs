const fs=require('node:fs'),assert=require('node:assert/strict');
const path=require('node:path'),{pathToFileURL}=require('node:url');
(async()=>{
 const THREE=await import(pathToFileURL(path.resolve('dist/vendor/three.module.js')).href);
 const source=fs.readFileSync('dist/renderer3d.js','utf8')
   .replace(/import \* as THREE from '[^']+';/,'')
   .replace('export class TrafficRenderer','class TrafficRenderer');
 const {TrafficRenderer,Batch}=new Function('THREE',source+'return {TrafficRenderer,Batch};')(THREE);
 const r=Object.create(TrafficRenderer.prototype);
 r.scene=new THREE.Scene();r.w=800;r.h=600;
 r.renderer={setPixelRatio(v){this.dpr=v;}};
 r.resize=()=>{};
 r.graphicQuality='medium';
 r.treeGroup=new THREE.Group();
 r.buildingGroup=new THREE.Group();
 r.camera=new THREE.OrthographicCamera(-12,12,9,-9,.1,1000);
 r.camera.position.set(0,30,20);r.camera.lookAt(0,0,0);
 r.cam={x:0,y:0,z:2};
 r.createCars();
 r.parking={parkingIsMoving:()=>false,parkingSlotPose:()=>null,citizenCarColor:()=> '#fff'};
 const vehicles=new Map([[1,{id:1,citizenId:1,phase:'driving',x:.5,z:.5}]]);
 const state={vehicles,citizens:new Map(),buildings:new Map()};
 const position=v=>({x:v.x,y:v.z,angle:0});
 r.cars(state,position,null,()=> 'green',null);
 assert.equal(r.carLODStats.medium,1,'medium must downgrade car at closer zoom than before');
 const batch=new Batch({detailGroups:true});
 batch.box('#abcabc',0,.8,0,1.6,1.5,1.2,0,55);
 batch.box('#ffcc00',.7,1,0,.02,.03,.08,0,55);
 batch.add(new THREE.BoxGeometry(1,1,1),'#77aa66',.5,.5,.3,.25,.35,.25,0,0,0,55,false,'foliage');
 r.buildingGroup.add(batch.build());
 const meshes=[];r.buildingGroup.traverse(o=>{if(o.isInstancedMesh)meshes.push(o);});
 assert.equal(meshes.length,3,'building batches separate normal shell, small trims and foliage');
 const fine=meshes.find(x=>x.userData.fineBuildingDetail);
 const foliage=meshes.find(x=>x.userData.isBuildingTree);
 const base=meshes.find(x=>!x.userData.fineBuildingDetail&&!x.userData.isBuildingTree);
 assert(fine&&base&&foliage);
 r.updateBuildingDetailLOD({z:2});
 assert.equal(fine.visible,true);
 r.updateBuildingDetailLOD({z:0.5});
 assert.equal(fine.visible,false,'medium hides tiny trim when far');
 assert.equal(base.visible,true,'walls and roof must remain');
 assert.equal(r.setGraphicQuality('veryHigh'),true);
 assert.equal(r.renderer.dpr,Math.min(global.devicePixelRatio||1,1.6));
 r.updateBuildingDetailLOD({z:0.5});
 assert.equal(fine.visible,true,'very high retains every building detail');
 assert.equal(foliage.visible,true,'very high preserves decorative planting');
 r.cars(state,position,null,()=> 'green',null);
 assert.equal(r.carLODStats.near,1,'very high retains full car model regardless of zoom');
 assert.equal(r.setGraphicQuality('low'),true);
 assert.equal(r.treeGroup.visible,false,'low skips all visible trees');
 assert.equal(r.renderer.dpr,.72,'low physically lowers framebuffer resolution at all zooms');
 r.updateBuildingDetailLOD({z:2});
 assert.equal(fine.visible,false);
 assert.equal(foliage.visible,false,'low hides building foliage without deleting state');
 r.cars(state,position,null,()=> 'green',null);
 assert.equal(r.carLODStats.far,1,'low uses far proxy even when camera close');
 assert.equal(base.visible,true);
 assert.equal(r.setGraphicQuality('medium'),true);
 assert.equal(r.treeGroup.visible,true,'trees reappear without save changes');
 r.updateBuildingDetailLOD({z:2});
 assert.equal(foliage.visible,true,'returning to medium restores building greenery');
 assert.equal(r.setGraphicQuality('invalid'),false,'reject unknown presets');

 const fixture=fs.readFileSync('work/test-tourism.cjs','utf8')
  .split('const results=[]')[0].replace('return{game,get};','return{game,get,context};');
 const {game,get,context}=new Function('require',fixture+'return boot();')(require);
 assert.equal(game.graphicQuality,'medium','default graphics should be medium');
 game.openMainMenu();
 assert.match(get('dialogContent').innerHTML,/id="graphicsMenu"/);
 game.openGraphicsMenu();
 assert.match(get('dialogContent').innerHTML,/data-graphics-quality="veryHigh"/);
 assert.match(get('dialogContent').innerHTML,/data-graphics-quality="medium"/);
 assert.match(get('dialogContent').innerHTML,/data-graphics-quality="low"/);
 const carsBefore=game.state.vehicles.size,treesBefore=game.state.plantedTrees.length;
 assert.equal(game.applyGraphicQuality('low'),true);
 assert.equal(game.graphicQuality,'low');
 assert.equal(game.state.plantedTrees.length,treesBefore,'low must not delete planted trees');
 assert.equal(game.state.vehicles.size,carsBefore,'quality switch must not modify simulation');
 assert.equal(game.applyGraphicQuality('veryHigh'),true);
 assert.equal(game.graphicQuality,'veryHigh');
 assert.equal(game.applyGraphicQuality('unknown'),false);
 console.log('Graphics quality: veryHigh/medium/low, car LOD, real framebuffer resolution, mild building trim filtering, trees preservation and menu passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
