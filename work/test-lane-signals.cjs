function sample(t){
 game.state.time=base+t;
 const st=game.signalStatus(center);
 let activeApproaches=0;
 for(const slot of slots){
  const colors=Array.from({length:slot.lanes},(_,lane)=>game.signalColor(center,slot.incoming,lane));
  assert.equal(new Set(colors).size,1,'all lanes on one approach share one signal indication');
  if(colors[0]==='green'){activeApproaches++;assert.equal(st.incoming,slot.incoming);assert.equal(colors.filter(c=>c==='green').length,slot.lanes);}
  for(let lane=0;lane<slot.lanes;lane++)assert.equal(game.signalAllows(center,slot.incoming,lane),colors[0]==='green');
 }
 assert(activeApproaches<=1,'opposing approaches can never share green');
 if(st.yellow||st.phase===-1)assert.equal(activeApproaches,0,'yellow/all-red denies entry');
 else assert.equal(activeApproaches,1,'one full approach must be green');
 return st;
}
